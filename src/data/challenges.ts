/**
 * Returns a randomized challenge based on whether the "coquin" theme is active.
 * If isCoquin is true, guarantees a sensual / spicy challenge.
 */
export function getRandomChallenge(isCoquin: boolean, excludeId?: string): LoveChallenge {
  const pool = isCoquin ? COQUIN_CHALLENGES : ROMANTIC_CHALLENGES;
  const filtered = pool.filter(c => c.id !== excludeId);
  const choiceList = filtered.length > 0 ? filtered : pool;
  const index = Math.floor(Math.random() * choiceList.length);
  return choiceList[index];
}
